    <p><strong>Dernière mise à jour :</strong> 25 novembre 2026</p>

    <h2>1. Introduction</h2>

    <p>
        FSI Hub est une plateforme numérique destinée à accompagner
        la communauté de la Faculté des Sciences Informatiques (FSI)
        de l'Université Catholique du Congo (UCC).
    </p>

    <p>
        La présente politique de confidentialité explique comment
        FSI Hub collecte, utilise, conserve et protège les données
        personnelles de ses utilisateurs.
    </p>

    <h2>2. Données personnelles collectées</h2>

    <p>
        Dans le cadre de l'utilisation de FSI Hub, certaines
        informations peuvent être collectées, notamment :
    </p>

    <ul>
        <li>Le nom et le prénom de l'utilisateur ;</li>
        <li>L'adresse électronique ;</li>
        <li>L'identifiant du compte utilisateur ;</li>
        <li>Les informations nécessaires à l'authentification ;</li>
        <li>Les informations communiquées lors de l'utilisation
            des différents services de la plateforme.</li>
    </ul>

    <p>
        Lorsque l'utilisateur choisit de se connecter avec Facebook,
        FSI Hub peut recevoir les informations autorisées par
        Facebook, notamment le nom, l'adresse électronique
        lorsqu'elle est disponible, et l'identifiant Facebook.
    </p>

    <h2>3. Utilisation des données</h2>

    <p>Les données personnelles sont utilisées pour :</p>

    <ul>
        <li>Créer et gérer les comptes utilisateurs ;</li>
        <li>Permettre l'authentification et la connexion ;</li>
        <li>Identifier les utilisateurs de la plateforme ;</li>
        <li>Fournir les services et fonctionnalités de FSI Hub ;</li>
        <li>Améliorer la sécurité et le fonctionnement de la plateforme ;</li>
        <li>Communiquer avec les utilisateurs lorsque cela est nécessaire.</li>
    </ul>

    <h2>4. Authentification avec Facebook</h2>

    <p>
        FSI Hub propose une fonctionnalité de connexion avec Facebook
        afin de simplifier l'accès à la plateforme.
    </p>

    <p>
        Lorsque cette méthode est utilisée, certaines informations
        du profil Facebook peuvent être transmises à FSI Hub,
        conformément aux autorisations accordées par l'utilisateur.
    </p>

    <p>
        Ces informations sont utilisées dans le cadre de
        l'authentification et de la gestion du compte utilisateur.
    </p>

    <p>
        FSI Hub n'utilise pas cette fonctionnalité pour publier
        automatiquement du contenu sur le profil Facebook
        de l'utilisateur.
    </p>

    <h2>5. Conservation des données</h2>

    <p>
        Les données personnelles sont conservées pendant la durée
        nécessaire à la fourniture des services de FSI Hub,
        sous réserve des obligations légales applicables.
    </p>

    <p>
        Les utilisateurs peuvent demander la suppression de leurs
        données personnelles conformément à la procédure décrite
        dans notre page dédiée.
    </p>

    <h2>6. Partage des données</h2>

    <p>
        FSI Hub ne vend pas les données personnelles de ses utilisateurs.
    </p>

    <p>
        Les données peuvent être traitées par des prestataires
        techniques intervenant dans l'hébergement et le fonctionnement
        de la plateforme, dans la mesure nécessaire à la fourniture
        des services.
    </p>

    <h2>7. Sécurité des données</h2>

    <p>
        Des mesures techniques et organisationnelles raisonnables
        sont mises en œuvre afin de protéger les données personnelles
        contre les accès non autorisés, la perte, la modification
        ou la divulgation.
    </p>

    <h2>8. Droits des utilisateurs</h2>

    <p>
        Chaque utilisateur peut demander l'accès à ses données,
        leur rectification ou leur suppression, dans les conditions
        prévues par les règles applicables.
    </p>

    <h2>9. Suppression des données personnelles</h2>

    <p>
        Pour demander la suppression de votre compte ou de vos
        données personnelles, consultez notre page :
    </p>

    <p>
        <a href="https://frnagrmi.fsiucc.com/suppression-donnees">
            Procédure de suppression des données
        </a>
    </p>

    <h2>10. Modifications de la politique</h2>

    <p>
        Cette politique peut être modifiée afin de tenir compte
        des évolutions de FSI Hub ou des exigences applicables.
        Les modifications seront publiées sur cette page.
    </p>

