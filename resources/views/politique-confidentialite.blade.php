    <p><strong>Dernière mise à jour :</strong> 25 novembre 2026</p>

    <h2>1. Introduction</h2>

    <p>
        FSI Hub est une plateforme numérique destinée à accompagner
        les étudiants et les membres de la communauté de la Faculté
        des Sciences Informatiques (FSI) de l'Université Catholique
        du Congo (UCC).
    </p>

    <p>
        La présente politique de confidentialité explique comment
        FSI Hub collecte, utilise, stocke, conserve et protège les
        données personnelles de ses utilisateurs dans le cadre
        de la fourniture de ses services.
    </p>

    <p>
        En utilisant FSI Hub, l'utilisateur est invité à prendre
        connaissance de la présente politique afin de comprendre
        les pratiques relatives au traitement de ses données
        personnelles.
    </p>

    <h2>2. Données personnelles collectées</h2>

    <p>
        Dans le cadre de la création d'un compte et de l'utilisation
        des fonctionnalités de FSI Hub, les données personnelles
        suivantes peuvent être collectées :
    </p>

    <ul>
        <li>Nom ;</li>
        <li>Postnom ;</li>
        <li>Prénom ;</li>
        <li>Adresse électronique (e-mail) ;</li>
        <li>Numéro de téléphone ;</li>
        <li>Photo de profil ;</li>
        <li>Matricule de l'Université Catholique du Congo ;</li>
        <li>Identifiants et informations nécessaires à l'authentification.</li>
    </ul>

    <p>
        Ces informations sont principalement fournies directement
        par l'utilisateur lors de son inscription ou de la mise à
        jour de son profil. Certaines informations peuvent également
        être obtenues par l'intermédiaire du service d'authentification
        Google lorsque cette méthode de connexion est utilisée.
    </p>

    <h2>3. Finalités du traitement des données</h2>

    <p>
        Les données personnelles collectées sont utilisées pour
        assurer le fonctionnement de FSI Hub et permettre aux
        utilisateurs de bénéficier de ses différents services.
    </p>

    <p>Elles servent notamment à :</p>

    <ul>
        <li>Créer et gérer les comptes utilisateurs ;</li>
        <li>Authentifier les utilisateurs et gérer leurs connexions ;</li>
        <li>Identifier les étudiants au moyen de leur matricule UCC ;</li>
        <li>Permettre l'accès aux cours et aux ressources pédagogiques ;</li>
        <li>Mettre à disposition les anciens travaux pratiques (TP) ;</li>
        <li>Mettre à disposition les anciens travaux dirigés (TD) ;</li>
        <li>Permettre la consultation des anciens examens ;</li>
        <li>Diffuser les actualités et les informations relatives à la faculté ;</li>
        <li>Donner accès aux tutoriels et aux ressources d'apprentissage ;</li>
        <li>Permettre la consultation des résultats académiques ;</li>
        <li>Assurer la sécurité et le bon fonctionnement de la plateforme.</li>
    </ul>

    <h2>4. Authentification avec Google</h2>

    <p>
        FSI Hub propose une fonctionnalité d'authentification avec
        Google afin de faciliter la connexion des utilisateurs
        à la plateforme.
    </p>

    <p>
        Lorsque l'utilisateur choisit de se connecter avec son
        compte Google, certaines informations de son profil sont
        transmises à FSI Hub, notamment :
    </p>

    <ul>
        <li>Son adresse électronique ;</li>
        <li>Son nom et son prénom ;</li>
        <li>Sa photo de profil.</li>
    </ul>

    <p>
        Ces informations sont utilisées pour identifier l'utilisateur,
        faciliter son authentification et assurer la création ou
        la gestion de son compte FSI Hub.
    </p>

    <p>
        L'authentification repose sur les mécanismes de connexion
        sécurisés proposés par Google. FSI Hub ne reçoit ni ne
        stocke le mot de passe du compte Google de l'utilisateur.
    </p>

    <p>
        Les informations obtenues par l'intermédiaire de Google
        sont utilisées uniquement dans le cadre des fonctionnalités
        proposées par FSI Hub et conformément aux autorisations
        accordées par l'utilisateur.
    </p>

    <p>
        L'utilisation des services Google reste également soumise
        aux règles et à la politique de confidentialité de Google.
    </p>

    <h2>5. Stockage et hébergement des données</h2>

    <p>
        Les données personnelles des utilisateurs sont enregistrées
        dans une base de données hébergée sur un serveur auprès
        de l'hébergeur o2switch.
    </p>

    <p>
        Cet hébergement permet d'assurer le stockage des informations
        nécessaires au fonctionnement de FSI Hub et à la gestion
        des comptes utilisateurs.
    </p>

    <p>
        Les mots de passe des comptes créés directement sur FSI Hub
        sont protégés au moyen de mécanismes de hachage cryptographique.
        Ils ne sont donc pas enregistrés sous leur forme originale
        en texte brut.
    </p>

    <h2>6. Durée de conservation des données</h2>

    <p>
        Les données personnelles sont conservées pendant toute
        la durée d'activité du compte utilisateur, aussi longtemps
        qu'elles sont nécessaires à la fourniture des services
        de FSI Hub.
    </p>

    <p>
        Lorsqu'un utilisateur demande la suppression de son compte,
        les données personnelles associées sont supprimées dans
        un délai raisonnable après vérification et traitement
        de la demande, sous réserve des éventuelles obligations
        légales ou nécessités techniques justifiant temporairement
        leur conservation.
    </p>

    <p>
        Les données qui ne sont plus nécessaires à la fourniture
        des services ou à la gestion du compte n'ont pas vocation
        à être conservées indéfiniment.
    </p>

    <h2>7. Partage et communication des données</h2>

    <p>
        FSI Hub ne vend, ne loue et ne commercialise pas les données
        personnelles de ses utilisateurs.
    </p>

    <p>
        Les données personnelles ne sont pas communiquées à des
        tiers à des fins commerciales ou publicitaires.
    </p>

    <p>
        Certaines informations peuvent toutefois être échangées
        avec Google lorsque l'utilisateur utilise la fonctionnalité
        d'authentification Google.
    </p>

    <p>
        L'hébergeur o2switch intervient également dans le cadre
        de l'hébergement technique de la plateforme et du stockage
        des données.
    </p>

    <h2>8. Sécurité et protection des données</h2>

    <p>
        FSI Hub met en œuvre des mesures techniques et des mécanismes
        de sécurité destinés à protéger les données personnelles
        contre les accès non autorisés, la perte, la modification,
        la divulgation ou toute autre forme de traitement non autorisé.
    </p>

    <p>Ces mesures comprennent notamment :</p>

    <ul>
        <li>
            Le hachage cryptographique des mots de passe afin
            d'éviter leur stockage en clair ;
        </li>
        <li>
            La mise en place de protections contre les attaques
            de type Cross-Site Request Forgery (CSRF) ;
        </li>
        <li>
            La protection contre les injections SQL grâce aux
            mécanismes de requêtes paramétrées et aux outils
            de gestion de base de données utilisés ;
        </li>
        <li>
            La validation et la vérification des données transmises
            par les utilisateurs ;
        </li>
        <li>
            La gestion des authentifications et des autorisations
            d'accès aux différentes fonctionnalités ;
        </li>
        <li>
            L'utilisation du protocole HTTPS pour sécuriser
            les communications avec la plateforme.
        </li>
    </ul>

    <p>
        Malgré ces mesures, aucun système informatique ou mécanisme
        de transmission de données sur Internet ne peut garantir
        une sécurité absolue. FSI Hub s'efforce néanmoins de
        maintenir un niveau de protection adapté aux données
        traitées et aux risques identifiés.
    </p>

    <h2>9. Droits des utilisateurs</h2>

    <p>
        Chaque utilisateur dispose de la possibilité d'exercer
        les droits suivants concernant ses données personnelles :
    </p>

    <ul>
        <li>Consulter les données personnelles associées à son compte ;</li>
        <li>Demander la rectification des informations inexactes ;</li>
        <li>Modifier les informations personnelles modifiables ;</li>
        <li>Demander la suppression de son compte ;</li>
        <li>Demander la suppression de ses données personnelles.</li>
    </ul>

    <p>
        Ces demandes peuvent être adressées à l'équipe responsable
        de FSI Hub par courrier électronique à l'adresse indiquée
        dans la section Contact.
    </p>

    <h2>10. Suppression du compte et des données personnelles</h2>

    <p>
        Tout utilisateur souhaitant supprimer son compte ou demander
        la suppression de ses données personnelles peut effectuer
        une demande auprès de l'équipe FSI Hub.
    </p>

    <p>
        Une page dédiée présente les modalités à suivre pour
        effectuer cette démarche.
    </p>

    <p>
        <a href="https://frnagrmi.fsiucc.com/suppression-donnees">
            Consulter la procédure de suppression des données
        </a>
    </p>

    <p>
        La demande sera examinée et traitée conformément aux
        modalités de suppression prévues par FSI Hub.
    </p>

    <h2>11. Services et contenus externes</h2>

    <p>
        FSI Hub peut intégrer ou proposer des contenus provenant
        de services externes, notamment des vidéos et tutoriels
        hébergés sur YouTube.
    </p>

    <p>
        La consultation de ces contenus peut entraîner des
        interactions avec les services concernés. Dans ce cas,
        les politiques de confidentialité et les conditions
        d'utilisation de ces plateformes externes s'appliquent
        également.
    </p>

    <h2>12. Modifications de la politique de confidentialité</h2>

    <p>
        La présente politique de confidentialité peut être mise
        à jour lorsque des évolutions importantes interviennent
        dans les fonctionnalités de FSI Hub, les pratiques de
        traitement des données personnelles ou les exigences
        réglementaires applicables.
    </p>

    <p>
        Toute nouvelle version sera publiée sur cette page
        et accompagnée de sa date de dernière mise à jour.
    </p>

